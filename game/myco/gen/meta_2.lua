      end
    end
    i = i + 1
  end
  local mc = cols[gm.div(cols_n, 2)]
  local axis_t = tail + 1.2
  local axis_reach = vis(self, other, "logo_axis_reach")
  if gm.bool(mc.has) then
    local top_a = logo_anchor(self, other, m, cx, mc.top)
    local bot_a = logo_anchor(self, other, m, cx, mc.bottom)
    logo_grow_thorn(self, other, m, top_a.x, top_a.y, 90, axis_reach * 0.8,
      vis(self, other, "logo_nib") * 0.5, top_a.half, 0, axis_t, seed + 11)
    logo_grow_strand(self, other, m, bot_a.x, bot_a.y, 270, axis_reach,
      vis(self, other, "logo_nib") * 0.55, bot_a.half, 0, axis_t, 0, 0, 0.5, 0.5, 12, seed + 12)
    local foot_y = bot_a.y + axis_reach * 0.62
    local foot_w = vis(self, other, "logo_nib") * 0.55 * 0.27083691323011094 * 0.5
    logo_grow_strand(self, other, m, bot_a.x, foot_y, 180, axis_reach * 0.34,
