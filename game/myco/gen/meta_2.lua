    end
    ri = ri + 1
  end
  m.duration = tail + 3
  return m
end

-- gml_Script_logo_draw_ribbon @ 0x1401ca800
function logo_draw_ribbon(self, other, path, ox, oy, scale, p)
  if ox == nil then ox = gm.undefined end
  if oy == nil then oy = gm.undefined end
  if scale == nil then scale = gm.undefined end
  if p == nil then p = gm.undefined end
  if p <= 0 then
    return
  end
  local segs = gm.clamp(gm.ceil(path.total * scale / 7), 8, 48)
  local ang = vis(self, other, "logo_pen_angle")
  local hn = path.nib * 0.5 * scale
  local minpx = vis(self, other, "logo_min_pixels")
  gm.draw_primitive_begin(gm.pr_trianglestrip)
  local i = 0
  while i <= segs do
    local t = i / segs * p
    local pt = logo_path_at(self, other, path, t)
    local taper
    if p >= 1 then
      taper = 1
    else
      taper = gm.clamp((p - t) / 0.06, 0, 1)
    end
    local h = hn * taper
    local dx = gm.lengthdir_x(h, ang)
    local dy = gm.lengthdir_y(h, ang)
    local thick = h * math.abs(gm.dsin(pt.dir - ang))
    if thick < minpx then
      dx = dx + gm.lengthdir_x(minpx - thick, pt.dir + 90)
      dy = dy + gm.lengthdir_y(minpx - thick, pt.dir + 90)
    end
    local px = ox + pt.x * scale
    local py = oy + pt.y * scale
    gm.draw_vertex(px + dx, py + dy)
    gm.draw_vertex(px - dx, py - dy)
    i = i + 1
  end
  gm.draw_primitive_end()
end
