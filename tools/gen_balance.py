#!/usr/bin/env python3
"""Generate rust/crates/myco_core/src/balance_tables.rs from the LÖVE port's balance sources.

Reads the struct constructors behind balance_defaults (core_1.lua), visual_defaults and
worldgen_defaults (core_3.lua) plus the argument lists those defaults pass in, and writes the
tables as sorted Rust constants (binary-searched by key).

Usage: python3 -I tools/gen_balance.py [--check]   (--check: exit 1 if the file is stale)
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GEN = ROOT / "game" / "myco" / "gen"
OUT = ROOT / "rust" / "crates" / "myco_core" / "src" / "balance_tables.rs"

ASSIGN_RE = re.compile(r"^\s*self\.(\w+) = (.+?)\s*$")
NUM_RE = re.compile(r"^-?(\d+\.?\d*|\.\d+)([eE][-+]?\d+)?$")


def function_body(src, name):
    m = re.search(r"^function " + re.escape(name) + r"\(.*?\)\n(.*?)^end\n", src, re.M | re.S)
    if not m:
        raise SystemExit(f"function {name} not found")
    return m.group(1)


def split_args(s):
    out, depth, cur = [], 0, ""
    for ch in s:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out


def parse_value(text, args, where):
    text = text.strip()
    if text in args:
        text = args[text]
    if text == "true":
        return 1.0
    if text == "false":
        return 0.0
    if NUM_RE.match(text):
        return float(text)
    m = re.match(r"^gm\.array\((.*)\)$", text, re.S)
    if m:
        return [parse_value(a, {}, where) for a in split_args(m.group(1))]
    raise SystemExit(f"{where}: cannot parse value {text!r}")


def defaults_args(src, defaults_fn, struct_fn):
    """Positional arguments that `defaults_fn` passes to gm.new(struct_fn, ...), as a0..aN."""
    body = function_body(src, defaults_fn)
    m = re.search(r"gm\.new\(" + re.escape(struct_fn) + r",(.*)\)\s*$", body, re.S)
    if not m:
        return {}
    return {f"a{i}": a for i, a in enumerate(split_args(m.group(1)))}


def table(src, struct_fn, defaults_fn):
    args = defaults_args(src, defaults_fn, struct_fn)
    vals = {}
    for line in function_body(src, struct_fn).splitlines():
        if "== nil then" in line:
            continue
        m = ASSIGN_RE.match(line)
        if not m:
            continue
        vals[m.group(1)] = parse_value(m.group(2), args, f"{struct_fn}.{m.group(1)}")
    return vals


def rust_f64(x):
    r = repr(float(x))
    if r in ("inf", "-inf", "nan"):
        raise SystemExit(f"non-finite value {r}")
    if "." not in r and "e" not in r:
        r += ".0"
    return r


def emit(name, vals, kind):
    lines = []
    if kind == "num":
        lines.append(f"pub(crate) const {name}: &[(&str, f64)] = &[")
        for k in sorted(vals):
            v = vals[k]
            if isinstance(v, list):
                raise SystemExit(f"{name}.{k}: array in a numeric table")
            lines.append(f'    ("{k}", {rust_f64(v)}),')
    else:
        lines.append(f"pub(crate) const {name}: &[(&str, TableVal)] = &[")
        for k in sorted(vals):
            v = vals[k]
            if isinstance(v, list):
                items = ", ".join(rust_f64(x) for x in v)
                lines.append(f'    ("{k}", TableVal::Arr(&[{items}])),')
            else:
                lines.append(f'    ("{k}", TableVal::Num({rust_f64(v)})),')
    lines.append("];")
    return "\n".join(lines)


def generate():
    core1 = (GEN / "core_1.lua").read_text()
    core3 = (GEN / "core_3.lua").read_text()
    bal = table(core1, "___struct___8__balance_defaults__scr_balance", "balance_defaults")
    vis = table(core3, "___struct___283__visual_defaults__scr_visual", "visual_defaults")
    wld = table(core3, "___struct___366__worldgen_defaults__scr_worldgen", "worldgen_defaults")
    header = (
        "// @generated by tools/gen_balance.py from game/myco/gen/core_1.lua (balance_defaults) and\n"
        "// core_3.lua (visual_defaults, worldgen_defaults). Do not edit: rerun the generator.\n"
        "// Keys are sorted for binary search; `true` is stored as 1.0.\n\n"
        "use super::TableVal;\n\n"
    )
    return header + "\n\n".join([
        emit("BAL_DEFAULTS", bal, "num"),
        emit("VIS_DEFAULTS", vis, "val"),
        emit("WLD_DEFAULTS", wld, "val"),
    ]) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if the generated file is stale")
    args = ap.parse_args(argv)
    text = generate()
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT} is stale: run tools/gen_balance.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
